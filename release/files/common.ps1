# Shared by install.ps1 (release package) and build.ps1 (repository).

$name = "l4d2-scaling-fix"
# folder in "Left 4 Dead 2" that holds the VPK, and the search path in gameinfo.txt
$modDir = "scaling_fix"
# Generated server browser layouts carry this in a comment in the first line.
# A layout without it is Valve's
$marker = "generated by $name"

function Find-Game {
	$steam = (Get-ItemProperty "HKCU:\Software\Valve\Steam" -ErrorAction SilentlyContinue).SteamPath
	if (-not $steam) { throw "Steam not found in the registry - pass the game folder with -Game" }
	$libs = @($steam)
	$vdf = Join-Path $steam "steamapps\libraryfolders.vdf"
	if (Test-Path $vdf) {
		$libs += [regex]::Matches((Get-Content $vdf -Raw), '"path"\s+"([^"]+)"') | ForEach-Object { $_.Groups[1].Value.Replace('\\', '\') }
	}
	foreach ($lib in $libs) {
		$dir = Join-Path $lib "steamapps\common\Left 4 Dead 2"
		if (Test-Path (Join-Path $dir "left4dead2\gameinfo.txt")) { return (Get-Item $dir).FullName }
	}
	throw "Left 4 Dead 2 not found in Steam's libraries - pass the game folder with -Game"
}

function Test-Generated($file) {
	return (Get-Content $file -TotalCount 1) -eq "// $marker"
}

# PatchVersion in steam.inf, e.g. 2.2.4.3
function Get-GameVersion($game) {
	$inf = Join-Path $game "left4dead2\steam.inf"
	if ((Test-Path $inf) -and ((Get-Content $inf -Raw) -match '(?m)^PatchVersion=(\S+)')) { return $Matches[1] }
	return ""
}

# screen height the game is set to, 0 when it has not written its video settings yet
function Get-GameResolution($game) {
	$video = Join-Path $game "left4dead2\cfg\video.txt"
	if ((Test-Path $video) -and ((Get-Content $video -Raw) -match '"setting\.defaultresheight"\s+"(\d+)"')) { return [int]$Matches[1] }
	return 0
}
