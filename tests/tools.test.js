const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const vfont = require('../tools/vfont.js');

// A vfont as the game's are built: XOR chain, then salt, salt length (counts itself), magic.
function makeVfont(plain, firstKey, salt) {
	const out = Buffer.alloc(plain.length);
	out[0] = plain[0] ^ firstKey;
	for (let i = 1; i < plain.length; i++) out[i] = plain[i] ^ ((out[i - 1] + 0xA7) & 0xFF);
	return Buffer.concat([out, salt, Buffer.from([salt.length + 1]), Buffer.from('VFONT1')]);
}

test('decode and encode are inverse', () => {
	const plain = Buffer.from([0, 1, 0, 0, ...Array.from({ length: 300 }, (_, i) => (i * 37 + 11) & 0xFF)]);
	const file = makeVfont(plain, 0x5C, Buffer.from([9, 8, 7, 6, 5]));
	assert.deepStrictEqual(vfont.decode(file), plain);
	assert.deepStrictEqual(vfont.encode(plain, file), file);
});

test('decode rejects a file without the magic', () => {
	assert.throws(() => vfont.decode(Buffer.from('not a font at all')), /not a vfont/);
});

// The game's own font, when the game is installed: L4D2_DIR, or Steam's default library.
function gameFont() {
	const dirs = [process.env.L4D2_DIR, 'C:\\Program Files (x86)\\Steam\\steamapps\\common\\Left 4 Dead 2'];
	for (const dir of dirs.filter(Boolean)) {
		const file = path.join(dir, 'left4dead2', 'resource', 'stubble-bold.vfont');
		if (fs.existsSync(file)) return file;
	}
	return null;
}

test("encode reproduces the game's stubble-bold.vfont byte for byte", { skip: !gameFont() && 'game not found' }, () => {
	const file = fs.readFileSync(gameFont());
	const ttf = vfont.decode(file);
	assert.strictEqual(ttf.readUInt32BE(0), 0x00010000); // TrueType
	assert.deepStrictEqual(vfont.encode(ttf, file), file);
});

test('scale-layout scales positions and sizes, keeps anchors, writes the marker', () => {
	const dir = fs.mkdtempSync(path.join(require('os').tmpdir(), 'scaling-fix-test-'));
	const input = path.join(dir, 'in.res'), output = path.join(dir, 'out.res');
	fs.writeFileSync(input, '"a"\r\n{\r\n\t"xpos"\t"r10"\r\n\t"ypos"\t"c-50"\r\n\t"wide"\t"75"\r\n\t"tall"\t"24"\r\n\t"zpos"\t"3"\r\n}\r\n');
	execFileSync(process.execPath, [path.join(__dirname, '..', 'tools', 'scale-layout.js'), input, output, '1.5', 'generated by test']);
	assert.strictEqual(fs.readFileSync(output, 'latin1'),
		'// generated by test\r\n"a"\r\n{\r\n\t"xpos"\t"r15"\r\n\t"ypos"\t"c-75"\r\n\t"wide"\t"113"\r\n\t"tall"\t"36"\r\n\t"zpos"\t"3"\r\n}\r\n');
	fs.rmSync(dir, { recursive: true });
});
